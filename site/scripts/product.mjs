// The generator. Every figure this site states about the product is read out of the
// product, because a number typed into prose is true on the day it is typed and silent
// about the day it stops being. The site's own copy states the reason; this file states
// the number.
//
// Three sources, all of them the ones the build already reads:
//   Directory.Build.props            the one declared version of every assembly here
//   src/**/*.csproj                  the two package ids, and which half takes which
//   src/Winwright/Verdicts/RunOutcome.cs   the outcomes AND their exit codes
//
// The last is the reason this generator exists at all. The enum's member values *are* the
// process exit codes — that is the product's own decision, written down in its summary —
// so a table of codes typed onto a web page is the same mapping written a third time, and
// a mapping written twice is a mapping that drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const repoDir = join(siteDir, "..");

const read = (...parts) => readFileSync(join(repoDir, ...parts), "utf8");

/** One value out of an MSBuild property group. Throws rather than defaulting: a version
 *  this generator invents agrees with nothing, which is the defect the property exists to
 *  prevent in the first place. */
function msbuildProperty(xml, name, where) {
  const m = new RegExp(`<${name}>([^<]+)</${name}>`).exec(xml);
  if (!m) throw new Error(`product: ${where} no longer declares <${name}>`);
  return m[1].trim();
}

const version = msbuildProperty(read("Directory.Build.props"), "Version", "Directory.Build.props");

const packages = [
  {
    id: msbuildProperty(read("src", "Winwright", "Winwright.csproj"), "PackageId", "Winwright.csproj"),
    takenBy: "harness",
  },
  {
    id: msbuildProperty(
      read("src", "Winwright.InApp", "Winwright.InApp.csproj"),
      "PackageId",
      "Winwright.InApp.csproj",
    ),
    takenBy: "app",
  },
];

// --- the verdicts, with their codes ---
// The enum members in file order, each with the value it declares and the first sentence of
// its <summary>. A member with no explicit value would be a code nobody wrote down, so it
// is refused here rather than rendered as a guess.
function outcomes(source) {
  const body = /enum\s+RunOutcome\s*\{([\s\S]*)\}/.exec(source);
  if (!body) throw new Error("product: RunOutcome.cs no longer declares an enum RunOutcome");

  const found = [];
  let doc = [];
  for (const raw of body[1].split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith("///")) {
      doc.push(line.replace(/^\/\/\/\s?/, ""));
      continue;
    }
    const member = /^([A-Z][A-Za-z]*)\s*=\s*(\d+)\s*,?$/.exec(line);
    if (member) {
      const summary = /<summary>([\s\S]*?)<\/summary>/.exec(doc.join(" "));
      if (!summary) {
        throw new Error(`product: ${member[1]} carries no <summary> to read`);
      }
      found.push({
        name: member[1],
        code: Number(member[2]),
        // the first sentence: the whole summary is a paragraph of reasoning, and a table
        // cell is one line. The reasoning stays in the source, where it is read by whoever
        // changes the value.
        meaning: `${summary[1].replace(/\s+/g, " ").trim().split(/(?<=\.)\s/)[0]}`,
      });
      doc = [];
      continue;
    }
    if (line.length > 0) doc = [];
  }
  if (found.length === 0) throw new Error("product: RunOutcome.cs declares no members");
  return found;
}

const verdicts = outcomes(read("src", "Winwright", "Verdicts", "RunOutcome.cs"));

const generated = `// GENERATED by scripts/product.mjs — do not edit.
//
// Read out of this repository's own source on every build, so a figure on the page cannot
// be true on the day it was typed and quietly wrong afterwards. The copy in site-content.ts
// states the reason; this file states the number.

export interface Verdict {
  /** the enum member, which is also the word a summary prints */
  readonly name: string;
  /** the member's value, which IS the process exit code */
  readonly code: number;
  /** the first sentence of the member's own XML summary */
  readonly meaning: string;
}

export interface Package {
  readonly id: string;
  /** "harness" is taken by the project driving the app; "app" by the app under test */
  readonly takenBy: "harness" | "app";
}

export const product = {
  version: ${JSON.stringify(version)},
  packages: ${JSON.stringify(packages, null, 2).replace(/\n/g, "\n  ")} as readonly Package[],
  verdicts: ${JSON.stringify(verdicts, null, 2).replace(/\n/g, "\n  ")} as readonly Verdict[],
} as const;
`;

const out = join(siteDir, "src", "lib", "product.generated.ts");
writeFileSync(out, generated);
console.log(
  `product: version ${version}, ${packages.length} package(s), ${verdicts.length} verdict(s)`
    + ` -> src/lib/product.generated.ts`,
);
