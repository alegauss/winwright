// The documentation area, at https://alegauss.github.io/winwright/docs/.
//
// Why an area at all: the README is the only prose this project publishes for a person, and it
// is one file of a thousand lines. A link to any part of it is a link to the whole thing, and
// everything narrower — `winwright_format`, `winwright_vocabulary`, the skill — answers only to
// an agent in a repository that has already installed the plugin. Somebody deciding whether to
// adopt this has neither, and deciding comes before installing.
//
// Why a second build rather than more sections on the pitch page next door: that page is one
// scroll, laid out once, with no sidebar, no per-page contents and no search. Starlight is those
// three and indexes them at build time, so nothing runs at serve time — which is the only shape
// a site published to GitHub Pages can have.
//
// Three joins, and `site/scripts/docs-area.test.mjs` reads this file and holds each of them
// against what declares it elsewhere, so none of them is remembered.
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";

// JOIN 1 — the base. GitHub Pages derives the site root from the repository name, so it is
// `/winwright/` and this area is one segment under it. It is declared in `site/vite.config.ts`
// and `site/src/routes.tsx` for the pitch page, and here for this one. Astro rewrites the links
// it generates and NOT the ones typed by hand, so an absolute href written into a page drops the
// prefix and 404s in production alone.
const BASE = "/winwright/docs";

// JOIN 2 — the output. The pitch page builds to `site/dist/` and this area builds into a
// subdirectory of it, because the deploy uploads that one directory and nothing else: an area
// writing anywhere outside it would be the half of the site no publish carries.
//
// Astro empties outDir before it writes, and `vite build` empties `dist/` — which is why this
// build runs *last* in the site's `build` script. Reordered, it is deleted by the step after it
// and the deploy goes green with the whole area missing.
const OUT_DIR = "../dist/docs";

export default defineConfig({
  site: "https://alegauss.github.io",
  base: BASE,
  outDir: OUT_DIR,

  integrations: [
    starlight({
      title: "winwright",
      description:
        "Driving a Windows desktop application from a test: what to install, how to declare a "
        + "project, how to write a case, and how to read what the run answered.",
      // Pagefind, indexed at build time — which is why search here needs no service to be up
      // and no account to exist.
      pagefind: true,
      social: [
        { icon: "github", label: "GitHub", href: "https://github.com/alegauss/winwright" },
      ],
      customCss: ["./src/styles/area.css"],
      // Named links rather than an autogenerated directory: these are the reads an adopter
      // needs, in the order they need them — what the tool answers, what to install, and the
      // first case they will run, and then the grammar that case is written in — which is the
      // one they come back to rather than read once. A directory listing would put them in
      // alphabetical order, which is an order nobody arrives in.
      sidebar: [
        { label: "What this is", link: "/" },
        { label: "Installing it", link: "/installing/" },
        { label: "Your first case", link: "/first-case/" },
        { label: "Addressing an element", link: "/locators/" },
        { label: "The case format", link: "/case-format/" },
      ],
      // No "edit this page": the footer already links the repository, and a second link per
      // page is a claim about a contribution flow this project has not written down.
      editLink: {},
      lastUpdated: true,
    }),
  ],
});
